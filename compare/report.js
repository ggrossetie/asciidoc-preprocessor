// Generates compare/REPORT.md: every corpus case, run through Asciidoctor
// (JS, and Ruby when the `asciidoctor` gem is installed) and through the
// transducer + the same parser. Usage: npm run compare

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import * as asciidoctor from 'asciidoctor';

import { cases } from './cases.js';
import { runCase, hasRubyAsciidoctor } from './harness.js';

const fence = (text) => '```\n' + (text === '' ? '(empty)' : text) + '\n```';
const ruby = hasRubyAsciidoctor();
const out = [];
out.push('# Comparison report: Asciidoctor vs. stream-clocked transducer', '');
out.push(`Generated by \`npm run compare\` — Asciidoctor.js ${JSON.parse(readFileSync(new URL('../node_modules/asciidoctor/package.json', import.meta.url))).version}${ruby ? `, ${ruby}` : ''}.`, '');
out.push('Each case is converted (1) by Asciidoctor directly and (2) by the transducer, whose output is then converted by the *same* Asciidoctor (with no directive left to evaluate). "same" means the rendered text is identical. See COMPARISON.md for the analysis.', '');
out.push(`| Case | Category | Title | JS | ${ruby ? 'Ruby | Ruby vs JS |' : ''}`);
out.push(`|------|----------|-------|----|${ruby ? '------|------------|' : ''}`);

const details = [];
for (const c of cases) {
  const r = await runCase(c, { ruby: Boolean(ruby) });
  out.push(`| [${c.id}](#${c.id.toLowerCase()}) | ${c.category} | ${c.title.replace(/\|/g, '\\|')} | ${r.verdictJs} | ${ruby ? `${r.verdictRuby} | ${r.rubyVsJs} |` : ''}`);
  details.push(`### ${c.id}`, '', `**${c.title}** (${c.category}) — JS: ${r.verdictJs}${ruby ? `, Ruby: ${r.verdictRuby}` : ''}`, '');
  details.push('Source (`main.adoc`):', '', fence(c.src.replace(/\n$/, '')), '');
  for (const [name, content] of Object.entries(c.files ?? {})) details.push(`\`${name}\`:`, '', fence(content.replace(/\n$/, '')), '');
  if (c.attributes) details.push(`API attributes: \`${JSON.stringify(c.attributes)}\``, '');
  if (c.safe) details.push(`Safe mode: \`${c.safe}\``, '');
  details.push('Asciidoctor.js rendered text:', '', fence(r.js.text), '');
  if (r.js.messages.length) details.push(`Asciidoctor.js log: ${r.js.messages.map((m) => `\`${m}\``).join(', ')}`, '');
  if (ruby && r.rubyVsJs === 'different') details.push('Asciidoctor (Ruby) rendered text:', '', fence(r.ruby.text), '');
  if (ruby && r.ruby.messages.length) details.push(`Asciidoctor (Ruby) log: ${r.ruby.messages.map((m) => `\`${m}\``).join(', ')}`, '');
  details.push('Transducer output (fed to the parser):', '', fence(r.transducer.lines.join('\n')), '');
  details.push('Transducer + parser rendered text:', '', fence(r.pipelineJs.text), '');
  if (r.transducer.diagnostics.length) details.push(`Transducer diagnostics: ${r.transducer.diagnostics.map((m) => `\`${m}\``).join(', ')}`, '');
}
out.push('', '## Cases', '', ...details);

const doc = await asciidoctor.load(':flag: yes\n\nifdef::flag[FLAG-VISIBLE]\n', { safe: 'unsafe', parse: false });
out.push('## Asciidoctor\'s reader without its parser', '', 'Drained on its own, Asciidoctor\'s `PreprocessorReader` turns `:flag: yes` + `ifdef::flag[FLAG-VISIBLE]` into:', '', fence(JSON.stringify(await doc.reader.readLines())), '', 'The transducer alone produces `[":flag: yes","","FLAG-VISIBLE"]`.', '');

const target = fileURLToPath(new URL('./REPORT.md', import.meta.url));
writeFileSync(target, out.join('\n'));
console.log(`wrote ${target}`);
